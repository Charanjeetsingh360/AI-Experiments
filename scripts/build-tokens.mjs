/**
 * build-tokens.js
 * Multi-mode Style Dictionary v5 build pipeline.
 *
 * Reads:
 *   tokens/sd-input/primitives.json                          → raw values (Design System file)
 *   tokens/sd-input/tokens/General/semantic-general.json     → font-family, font-weight, etc.
 *   tokens/sd-input/tokens/Color Theme/semantic-color.json   → Light (default)
 *   tokens/sd-input/tokens/Color Theme/Soothing Dark Mode.json
 *   tokens/sd-input/tokens/Color Theme/High Contrast.json
 *   tokens/sd-input/tokens/Color Theme/Stark Dark Mode - Testcase.json
 *   tokens/sd-input/tokens/Density Modes/semantic-density.json  → Normal/default
 *   tokens/sd-input/tokens/Density Modes/Large.json             → Comfortable
 *   tokens/sd-input/tokens/Density Modes/Small.json             → Compact
 *
 * Outputs:
 *   tokens/output/css/tokens.css  → all modes as CSS custom property blocks
 */

import StyleDictionary from 'style-dictionary';
import fs   from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const __dirname = path.dirname(new URL(import.meta.url).pathname);

const ROOT    = path.resolve(__dirname, '..');
const SD_IN   = path.join(ROOT, 'tokens', 'sd-input');
const TMP_DIR = path.join(ROOT, 'tokens', 'output', 'tmp');
const OUT_DIR = path.join(ROOT, 'tokens', 'output', 'css');

/* ─── helpers ─────────────────────────────────────────────────────────── */

function readJson(abs) {
  return JSON.parse(fs.readFileSync(abs, 'utf8'));
}

/** Strip any single top-level mode wrapper like "Primitives/Mode 1". */
function unwrap(obj) {
  const keys = Object.keys(obj);
  if (keys.length === 1 && (keys[0].includes('/') || /Mode \d/.test(keys[0]))) {
    return obj[keys[0]];
  }
  return obj;
}

/** Deep-merge any number of plain objects (right wins). */
function deepMerge(...sources) {
  const result = {};
  for (const src of sources) {
    for (const [k, v] of Object.entries(src)) {
      if (v && typeof v === 'object' && !Array.isArray(v) &&
          result[k] && typeof result[k] === 'object') {
        result[k] = deepMerge(result[k], v);
      } else {
        result[k] = v;
      }
    }
  }
  return result;
}

/** Build a single CSS block using Style Dictionary and return its content. */
async function buildBlock(tokens, selector, label) {
  const tmpFile = path.join(TMP_DIR, `${label}.css`);
  fs.mkdirSync(TMP_DIR, { recursive: true });

  const sd = new StyleDictionary({
    usesDtcg: true,
    tokens,
    platforms: {
      css: {
        transformGroup: 'css',
        buildPath: TMP_DIR + path.sep,
        files: [{
          destination: `${label}.css`,
          format: 'css/variables',
          options: {
            selector,
            outputReferences: false,   // resolve all aliases → raw values
          },
        }],
      },
    },
  });

  await sd.buildAllPlatforms();
  const css = fs.readFileSync(tmpFile, 'utf8');
  return css;
}

/* ─── main ────────────────────────────────────────────────────────────── */

async function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });

  // 1. Load base token sets
  const primitives   = unwrap(readJson(path.join(SD_IN, 'primitives.json')));
  const general      = readJson(path.join(SD_IN, 'tokens', 'General', 'semantic-general.json'));

  // 2. Mode definitions
  const COLOR_DIR   = path.join(SD_IN, 'tokens', 'Color Theme');
  const DENSITY_DIR = path.join(SD_IN, 'tokens', 'Density Modes');

  const colorModes = [
    { label: 'color-light',        selector: ':root, [data-theme="light"]',          file: path.join(COLOR_DIR, 'semantic-color.json') },
    { label: 'color-soothing-dark',selector: '[data-theme="soothing-dark"]',         file: path.join(COLOR_DIR, 'Soothing Dark Mode.json') },
    { label: 'color-high-contrast',selector: '[data-theme="high-contrast"]',         file: path.join(COLOR_DIR, 'High Contrast.json') },
    { label: 'color-stark-dark',   selector: '[data-theme="stark-dark"]',            file: path.join(COLOR_DIR, 'Stark Dark Mode - Testcase.json') },
  ];

  const densityModes = [
    { label: 'density-default',     selector: ':root, [data-density="default"], [data-density="normal"]', file: path.join(DENSITY_DIR, 'semantic-density.json') },
    { label: 'density-comfortable', selector: '[data-density="comfortable"], [data-density="large"]',     file: path.join(DENSITY_DIR, 'Large.json') },
    { label: 'density-compact',     selector: '[data-density="compact"], [data-density="small"]',         file: path.join(DENSITY_DIR, 'Small.json') },
  ];

  // 3. Build each mode block
  const parts = ['/* Generated by build-tokens.js — DO NOT EDIT MANUALLY */\n'];

  parts.push('/* ═══════════════════════ COLOR THEME MODES ═══════════════════════ */\n');
  for (const mode of colorModes) {
    console.log(`  Building ${mode.label}…`);
    const modeTokens = readJson(mode.file);
    const merged     = deepMerge(primitives, general, modeTokens);
    parts.push(await buildBlock(merged, mode.selector, mode.label));
  }

  parts.push('\n/* ═══════════════════════ DENSITY MODES ═════════════════════════ */\n');
  for (const mode of densityModes) {
    console.log(`  Building ${mode.label}…`);
    const modeTokens = readJson(mode.file);
    const merged     = deepMerge(primitives, general, modeTokens);
    parts.push(await buildBlock(merged, mode.selector, mode.label));
  }

  // 4. Write combined output
  const outFile = path.join(OUT_DIR, 'tokens.css');
  fs.writeFileSync(outFile, parts.join('\n'));

  // 5. Cleanup temp files
  fs.rmSync(TMP_DIR, { recursive: true, force: true });

  console.log('\n✅  tokens/output/css/tokens.css generated:');
  console.log(`    4 color theme blocks + 3 density blocks`);
  console.log(`    All aliases resolved to raw hex values\n`);
}

main().catch(err => { console.error('❌ Build failed:', err); process.exit(1); });
