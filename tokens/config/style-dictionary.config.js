/**
 * CS360 Style Dictionary Config — v5 compatible (ES Module)
 * Style Dictionary: v5.4.0
 */

import StyleDictionary from 'style-dictionary';

const PRIMITIVE_CATEGORIES = ['color','spacing','radius','font','elevation','focus','motion','size'];
const RAW_COLOR_KEYS = ['gray','blue','teal','green','red','yellow','orange','purple','rose','cyan','white','black'];
const SEMANTIC_CATEGORIES = ['color','density','component'];

// ── Transforms ──────────────────────────────────────────────────────────────

StyleDictionary.registerTransform({
  name: 'cs360/name/kebab',
  type: 'name',
  transform: (token) => `cs360-${token.path.join('-')}`,
});

StyleDictionary.registerTransform({
  name: 'cs360/value/px-to-rem',
  type: 'value',
  filter: (token) =>
    token.type === 'dimension' &&
    typeof (token.$value ?? token.value) === 'string' &&
    (token.$value ?? token.value).endsWith('px'),
  transform: (token) => {
    const raw = token.$value ?? token.value;
    const px = parseFloat(raw);
    return isNaN(px) ? raw : px === 0 ? '0' : `${+(px / 16).toFixed(4)}rem`;
  },
});

// ── Transform Groups ─────────────────────────────────────────────────────────

StyleDictionary.registerTransformGroup({
  name: 'cs360/css',
  transforms: ['cs360/name/kebab', 'cs360/value/px-to-rem', 'attribute/cti'],
});

StyleDictionary.registerTransformGroup({
  name: 'cs360/js',
  transforms: ['cs360/name/kebab', 'cs360/value/px-to-rem', 'attribute/cti'],
});

// ── Formats ──────────────────────────────────────────────────────────────────

StyleDictionary.registerFormat({
  name: 'cs360/css/variables',
  format: ({ dictionary, options }) => {
    const selector = options?.selector ?? ':root';
    const layer    = options?.layer    ?? 'Token';
    const source   = options?.source   ?? 'primitives';
    const lines = dictionary.allTokens.map((t) => {
      const desc = t.comment || t.description;
      return `  --${t.name}: ${t.value};${desc ? ` /* ${desc} */` : ''}`;
    });
    return [
      `/**`,
      ` * CS360 Design System — ${layer} Layer`,
      ` * Auto-generated by Style Dictionary v5. Do not edit.`,
      ` * Source: tokens/${source}.json`,
      ` */`,
      ``,
      `${selector} {`,
      ...lines,
      `}`,
      ``,
    ].join('\n');
  },
});

StyleDictionary.registerFormat({
  name: 'cs360/js/tailwind-map',
  format: ({ dictionary }) => {
    const entries = dictionary.allTokens.map(
      (t) => `  '${t.name}': 'var(--${t.name})',`
    );
    return [
      `/** CS360 Tailwind Token Map — auto-generated */`,
      `module.exports = {`,
      ...entries,
      `};`,
      ``,
    ].join('\n');
  },
});

StyleDictionary.registerFormat({
  name: 'cs360/json/flat',
  format: ({ dictionary }) => {
    const obj = {};
    dictionary.allTokens.forEach((t) => { obj[`--${t.name}`] = t.value; });
    return JSON.stringify(obj, null, 2) + '\n';
  },
});

// ── Filters ──────────────────────────────────────────────────────────────────

const isPrimitive = (t) => PRIMITIVE_CATEGORIES.includes(t.path[0]);
const isSemantic  = (t) =>
  SEMANTIC_CATEGORIES.includes(t.path[0]) &&
  !(t.path[0] === 'color' && RAW_COLOR_KEYS.includes(t.path[1]));

// ── Config ───────────────────────────────────────────────────────────────────

export default {
  source: ['tokens/primitives.json', 'tokens/semantic.json'],
  platforms: {

    'css/primitives': {
      transformGroup: 'cs360/css', prefix: 'cs360', buildPath: 'tokens/output/',
      files: [{ destination: 'primitives.css', format: 'cs360/css/variables', filter: isPrimitive,
        options: { selector: ':root', layer: 'Primitive', source: 'primitives' } }],
    },

    'css/semantic': {
      transformGroup: 'cs360/css', prefix: 'cs360', buildPath: 'tokens/output/',
      files: [{ destination: 'semantic.css', format: 'cs360/css/variables', filter: isSemantic,
        options: { selector: ':root', layer: 'Semantic', source: 'semantic' } }],
    },

    'js/tailwind': {
      transformGroup: 'cs360/js', prefix: 'cs360', buildPath: 'tokens/output/',
      files: [{ destination: 'tokens.js', format: 'cs360/js/tailwind-map' }],
    },

    'json/reference': {
      transformGroup: 'cs360/js', prefix: 'cs360', buildPath: 'tokens/output/',
      files: [{ destination: 'tokens.json', format: 'cs360/json/flat' }],
    },

    'css/angular-primitives': {
      transformGroup: 'cs360/css', prefix: 'cs360', buildPath: 'src/styles/tokens/',
      files: [{ destination: 'primitives.css', format: 'cs360/css/variables', filter: isPrimitive,
        options: { selector: ':root', layer: 'Primitive', source: 'primitives' } }],
    },

    'css/angular-semantic': {
      transformGroup: 'cs360/css', prefix: 'cs360', buildPath: 'src/styles/tokens/',
      files: [{ destination: 'semantic.css', format: 'cs360/css/variables', filter: isSemantic,
        options: { selector: ':root', layer: 'Semantic', source: 'semantic' } }],
    },

  },
};
